function bw = refine_band_pixel_graphcut(img, sp, bw_coarse, bandMask, finitePix, alpha, lambda_px, beta, k_intra, minSigma)
[H,W] = size(img);
imgv = img(:);
spv  = sp(:);
bw0v = bw_coarse(:);
idxFinite = finitePix(:);
v = imgv(idxFinite);
l = bw0v(idxFinite);
n1 = sum(l==1); n2 = sum(l==2);
mu1 = sum(v(l==1))/max(n1,1);
mu2 = sum(v(l==2))/max(n2,1);
s1 = sum((v(l==1)-mu1).^2)/max(n1,1);
s2 = sum((v(l==2)-mu2).^2)/max(n2,1);
sig1 = sqrt(max(s1, minSigma^2));
sig2 = sqrt(max(s2, minSigma^2));
band = bandMask(:);
nb = nnz(band);
map = zeros(H*W,1,'uint32');
map(band) = uint32(1:nb);
pidx = find(band);
Iband = imgv(pidx);
spBand = spv(pidx);
D1 = 0.5*((Iband-mu1).^2)/(sig1^2) + log(sig1);
D2 = 0.5*((Iband-mu2).^2)/(sig2^2) + log(sig2);
D1 = alpha * D1;
D2 = alpha * D2;
m = min(D1,D2);
D1 = max(D1-m,0);
D2 = max(D2-m,0);
D1(~isfinite(D1)) = 1e6;
D2(~isfinite(D2)) = 1e6;
band2 = reshape(band, H, W);
lin = reshape(1:H*W, H, W);
id  = reshape(uint32(map), H, W);
idL = id(:,1:W-1);
idR = id(:,2:W);
m_in = (idL>0) & (idR>0);
n1a = double(idL(m_in));
n1b = double(idR(m_in));
pL = lin(:,1:W-1);
pR = lin(:,2:W);
pL_in = pL(m_in);
pR_in = pR(m_in);
dI = imgv(pL_in) - imgv(pR_in);
wR = lambda_px * exp(-beta*(dI.^2));
sameSP = (spv(pL_in) == spv(pR_in));
wR(sameSP) = wR(sameSP) * k_intra;
idU = id(1:H-1,:);
idD = id(2:H,:);
m_in2 = (idU>0) & (idD>0);
n2a = double(idU(m_in2));
n2b = double(idD(m_in2));
pU = lin(1:H-1,:);
pD = lin(2:H,:);
pU_in = pU(m_in2);
pD_in = pD(m_in2);
dI2 = imgv(pU_in) - imgv(pD_in);
wD = lambda_px * exp(-beta*(dI2.^2));
sameSP2 = (spv(pU_in) == spv(pD_in));
wD(sameSP2) = wD(sameSP2) * k_intra;
es = [n1a; n2a];
et = [n1b; n2b];
w  = [wR;  wD];
w(~isfinite(w) | w<0) = 0;
bw0v = bw_coarse(:);
m_cross = band2(:,1:W-1) & ~band2(:,2:W);
if any(m_cross(:))
    pL2 = pL(m_cross);
    pR2 = pR(m_cross);
    nid = double(map(pL2));
    keep = (nid > 0);
    nid = nid(keep);
    pL2 = pL2(keep);
    pR2 = pR2(keep);
    dI = imgv(pL2) - imgv(pR2);
    wc = lambda_px * exp(-beta*(dI.^2));
    sameSPc = (spv(pL2) == spv(pR2));
    wc(sameSPc) = wc(sameSPc) * k_intra;
    fixedLab = bw0v(pR2);
    add1 = wc .* (fixedLab==2);
    add2 = wc .* (fixedLab==1);
    D1(nid) = D1(nid) + add1;
    D2(nid) = D2(nid) + add2;
end
m_cross2 = band2(1:H-1,:) & ~band2(2:H,:);
if any(m_cross2(:))
    pU2 = pU(m_cross2);
    pD2 = pD(m_cross2);
    nid = double(map(pU2));
    keep = (nid > 0);
    nid = nid(keep);
    pU2 = pU2(keep);
    pD2 = pD2(keep);
    dI = imgv(pU2) - imgv(pD2);
    wc = lambda_px * exp(-beta*(dI.^2));
    sameSPc2 = (spv(pU2) == spv(pD2));
    wc(sameSPc2) = wc(sameSPc2) * k_intra;
    fixedLab = bw0v(pD2);
    add1 = wc .* (fixedLab==2);
    add2 = wc .* (fixedLab==1);
    D1(nid) = D1(nid) + add1;
    D2(nid) = D2(nid) + add2;
end
m = min(D1,D2);
D1 = max(D1-m,0);
D2 = max(D2-m,0);
D1(~isfinite(D1))=1e6; D2(~isfinite(D2))=1e6;
x_band = graphcut_binary_potts(D1, D2, es, et, w);
bw = bw_coarse;
bw(pidx) = reshape(x_band, [], 1);
end
