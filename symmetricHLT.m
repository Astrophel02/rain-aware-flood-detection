function HLT = symmetricHLT(T1, T2)
det1 = T1.C11 .* T1.C22 - abs(T1.C12).^2;
det2 = T2.C11 .* T2.C22 - abs(T2.C12).^2;
forward = (T1.C22 ./ det1) .* T2.C11 ...
    - (T1.C12 ./ det1) .* conj(T2.C12) ...
    - conj(T1.C12 ./ det1) .* T2.C12 ...
    + (T1.C11 ./ det1) .* T2.C22;
reverse = (T2.C22 ./ det2) .* T1.C11 ...
    - (T2.C12 ./ det2) .* conj(T1.C12) ...
    - conj(T2.C12 ./ det2) .* T1.C12 ...
    + (T2.C11 ./ det2) .* T1.C22;
HLT = max(real(forward), real(reverse));
HLT(HLT < 2) = 2;
end
